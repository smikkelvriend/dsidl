#!/usr/bin/env python3
# Converts TTF fonts into anti-aliased 4-bit glyph tables for the DS renderer.
# Usage: python3 tools/mkfont.py <regular.ttf> <bold.ttf> > source/font_data.c
import sys
from PIL import Image, ImageDraw, ImageFont

REG, BOLD = sys.argv[1], sys.argv[2]
# (name, file, pixel size)
FONTS = [("small", REG, 10), ("body", REG, 12), ("bold", BOLD, 12),
         ("title", BOLD, 15), ("big", BOLD, 21)]
CODES = list(range(32, 127)) + list(range(160, 256))

out = []
out.append("// Generated by tools/mkfont.py from Poppins (SIL Open Font License)")
out.append('#include "font.h"\n')
names = []
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data = bytearray()
    glyphs = []
    for cp in CODES:
        ch = chr(cp)
        bbox = f.getbbox(ch)  # relative to origin at top of ascent
        adv = int(round(f.getlength(ch)))
        if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255)
        px = im.load()
        off = len(data)
        nib = []
        for y in range(h):
            for x in range(w):
                nib.append((px[x, y] + 8) // 17)  # 0..15
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            data.append(nib[i] | (nib[i + 1] << 4))
        glyphs.append((off, x0, y0, w, h, adv))
    out.append(f"static const unsigned char {name}_data[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const font_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        out.append("    {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    names.append((name, asc, desc))
    out.append("")

out.append("const font_t fonts[FONT_COUNT] = {")
for name, asc, desc in names:
    out.append(f"    {{ {name}_glyphs, {name}_data, {asc}, {desc} }},")
out.append("};")
print("\n".join(out))
